#!/usr/bin/env python3
"""Build db/migrations/004_taguig_seed.sql from the pipeline CSVs.

Sources (edit these, then rerun):
  pipeline/data/terms.csv         - council terms
  pipeline/data/term_members.csv  - people and their memberships per term
  pipeline/data/documents.csv     - ordinances, resolutions, executive orders

Usage: python3 scripts/openlgu/build-taguig-seed.py
"""

import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'pipeline' / 'data'
OUT = ROOT / 'db' / 'migrations' / '004_taguig_seed.sql'


def read(name):
    with open(DATA / name, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def sql(value):
    if value is None or value == '':
        return 'NULL'
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def slugify(text):
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


def insert(table, columns, rows):
    if not rows:
        return ''
    values = ',\n  '.join(
        '(' + ', '.join(sql(row[c]) for c in columns) + ')' for row in rows
    )
    return f'INSERT INTO {table} ({", ".join(columns)}) VALUES\n  {values};\n'


def main():
    terms = read('terms.csv')
    members = read('term_members.csv')
    documents = read('documents.csv')

    persons = {}
    memberships = []
    for m in members:
        persons.setdefault(m['person_id'], {
            'id': m['person_id'],
            'first_name': m['first_name'],
            'middle_name': m['middle_name'],
            'last_name': m['last_name'],
        })
        memberships.append({
            'id': f"{m['term_id']}_{m['person_id']}",
            'person_id': m['person_id'],
            'term_id': m['term_id'],
            'chamber': m['chamber'],
            'role': m['role'],
            'rank': int(m['rank']) if m['rank'] else None,
        })

    subjects = {}
    document_subjects = []
    for d in documents:
        for name in filter(None, d['subjects'].split('|')):
            sid = slugify(name)
            subjects[sid] = {'id': sid, 'name': name, 'slug': sid}
            document_subjects.append({'document_id': d['id'], 'subject_id': sid})
        d['term_id'] = d['term_id'] or None
        d['date_enacted'] = d['date_enacted'] or None
        d['source_type'] = 'website'
        d['publication_status'] = d['status'] or 'active'
        d['canonical_notes'] = d['notes'] or None

    parts = [
        '-- Taguig OpenLGU seed data',
        '-- Migration: 004_taguig_seed.sql',
        '--',
        '-- GENERATED by scripts/openlgu/build-taguig-seed.py from pipeline/data/*.csv.',
        '-- Do not edit by hand; edit the CSVs and rerun the script.',
        '',
        '-- terms.mayor / terms.vice_mayor are read by functions/api/openlgu/persons.ts.',
        'ALTER TABLE terms ADD COLUMN mayor TEXT REFERENCES persons(id);',
        'ALTER TABLE terms ADD COLUMN vice_mayor TEXT REFERENCES persons(id);',
        '',
        insert('persons', ['id', 'first_name', 'middle_name', 'last_name'],
               list(persons.values())),
        insert('terms', ['id', 'term_number', 'ordinal', 'name', 'start_date',
                         'end_date', 'year_range', 'mayor', 'vice_mayor'],
               [{**t, 'term_number': int(t['term_number'])} for t in terms]),
        insert('memberships', ['id', 'person_id', 'term_id', 'chamber', 'role', 'rank'],
               memberships),
        insert('subjects', ['id', 'name', 'slug'], list(subjects.values())),
        insert('documents', ['id', 'type', 'number', 'title', 'term_id',
                             'date_enacted', 'pdf_url', 'source_type',
                             'publication_status', 'canonical_notes'],
               documents),
        insert('document_subjects', ['document_id', 'subject_id'], document_subjects),
    ]
    OUT.write_text('\n'.join(parts), encoding='utf-8')
    print(f'Wrote {OUT.relative_to(ROOT)}: {len(persons)} persons, {len(terms)} terms, '
          f'{len(memberships)} memberships, {len(documents)} documents, '
          f'{len(subjects)} subjects')


if __name__ == '__main__':
    main()
